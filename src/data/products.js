// Helper: get featured products
export const getFeaturedProducts = () => products.filter((p) => p.featured);

// Helper: get trending products
export const getTrendingProducts = () => products.filter((p) => p.trending);

// Helper: get new arrivals
export const getNewArrivals = () => products.filter((p) => p.newArrival);

// Helper: get products by category slug
export const getProductsByCategory = (categorySlug) =>
  products.filter((p) => p.category === categorySlug);

// Helper: get product by id
export const getProductById = (id) =>
  products.find((p) => p.id === parseInt(id));

// Helper: get product by slug
export const getProductBySlug = (slug) =>
  products.find((p) => p.slug === slug);

// Helper: get related products
export const getRelatedProducts = (product, limit = 4) =>
  products
    .filter((p) => p.category === product.category && p.id !== product.id)
    .slice(0, limit);
